var assert = require("assert");
var fs = require("fs");
var path = require("path");
var root = path.join(__dirname, "..");
var permissions = require(path.join(root, "backend", "permissions"));
var server = fs.readFileSync(path.join(root, "backend", "server.js"), "utf8");
var schema = fs.readFileSync(path.join(root, "database", "schema.sql"), "utf8");
var migration = fs.readFileSync(path.join(root, "database", "migrate_sprint9_system_admin_no_facility.sql"), "utf8");
var setup = fs.readFileSync(path.join(root, "frontend", "setup.html"), "utf8");
var login = fs.readFileSync(path.join(root, "frontend", "js", "login.js"), "utf8");

assert.strictEqual(permissions.canDo("system_admin", "approve_facility_requests"), true);
assert.strictEqual(permissions.canDo("system_admin", "read_system_overview"), true);
assert.strictEqual(permissions.canDo("system_admin", "approve_staff"), false, "global IT admin must not approve facility staff");
assert.strictEqual(permissions.canDo("facility_admin", "approve_staff"), true);
assert.strictEqual(permissions.canDo("facility_admin", "approve_facility_requests"), false);
assert.match(schema, /facility_id\s+TEXT,\s+password_hash/s);
assert.match(schema, /role = 'system_admin' AND facility_id IS NULL/);
assert.match(migration, /UPDATE staff SET facility_id = NULL WHERE role = 'system_admin'/);
assert.match(migration, /ALTER TABLE audit_log ALTER COLUMN facility_id DROP NOT NULL/);
assert.match(server, /role='system_admin' AND facility_id IS NULL/);
assert.match(server, /role<>'system_admin'/);
assert.match(server, /VALUES\(\$1,\$2,\$3,'system_admin',NULL/);
assert.match(server, /req\.user\.facilityId \? await pool\.query/);
assert.match(server, /requirePermission\("approve_facility_requests"\)/);
assert.match(setup, /id="admin-contact"/);
assert.doesNotMatch(setup, /facility-name|facility-type|district/);
assert.match(login, /body\.loginType = "system_admin"/);
assert.match(login, /ehumure_facility_id.*, out\.data\.facilityId \|\| ""/);
console.log("Sprint 9 system administrator invariants passed.");
